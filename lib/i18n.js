/**
 * Format currency in Indonesian Rupiah
 */
export function formatRupiah(amount) {
  const numeric = Number(amount) || 0;
  return new Intl.NumberFormat("id-ID", {
    style: "currency",
    currency: "IDR",
    maximumFractionDigits: 0,
  }).format(numeric);
}

/**
 * Format date in Asia/Jakarta timezone
 */
export function formatDateTimeJakarta(dateString, locale = "id") {
  if (!dateString) return "-";
  try {
    const d = new Date(dateString);
    if (isNaN(d.getTime())) return "-";
    return new Intl.DateTimeFormat(locale === "en" ? "en-US" : "id-ID", {
      timeZone: "Asia/Jakarta",
      dateStyle: "medium",
      timeStyle: "short",
    }).format(d);
  } catch {
    return String(dateString);
  }
}

/**
 * Format simple date YYYY-MM-DD in Asia/Jakarta
 */
export function formatDateJakarta(dateString, locale = "id") {
  if (!dateString) return "-";
  try {
    const d = new Date(dateString);
    if (isNaN(d.getTime())) return "-";
    return new Intl.DateTimeFormat(locale === "en" ? "en-US" : "id-ID", {
      timeZone: "Asia/Jakarta",
      year: "numeric",
      month: "short",
      day: "numeric",
    }).format(d);
  } catch {
    return String(dateString);
  }
}

/**
 * Returns today's ISO date string (YYYY-MM-DD) in Asia/Jakarta timezone
 */
export function getTodayJakarta() {
  const now = new Date();
  const jakartaStr = now.toLocaleDateString("en-CA", { timeZone: "Asia/Jakarta" });
  return jakartaStr; // returns YYYY-MM-DD
}
